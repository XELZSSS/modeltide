const fs = require("fs");
const path = require("path");
const { createHash } = require("crypto");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "src", "shared", "config", "cache-version.gen.ts");
const GEN_HEADER = "// Generated by build/gen-cache-version.cjs — do not edit.\n";

const ROOTS = ["src/server", "src/shared"];

const EXCLUDED = [
  /\.test\.ts$/,
  /^src\/shared\/config\/cache-version\.gen\.ts$/,
  /^src\/shared\/i18n\//,
  /^src\/shared\/pwa\.ts$/,
  /^src\/shared\/config\/typography\.ts$/,
];

const CLIENT_ONLY = [
  "src/shared/utils/color.ts",
  "src/shared/utils/cost.ts",
  "src/shared/utils/hallucination.ts",
  "src/shared/utils/money.ts",
  "src/shared/utils/pricing.ts",
  "src/shared/utils/release-feed.ts",
  "src/shared/utils/text-format.ts",
];

const PINNED_DEPS = ["fast-xml-parser", "strnum"];

function fail(message) {
  console.error(`gen:cache-version ${message}`);
  process.exit(1);
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

function relative(abs) {
  return path.relative(ROOT, abs).split(path.sep).join("/");
}

function hashedFiles() {
  return ROOTS.flatMap((root) => walk(path.join(ROOT, root)))
    .map((abs) => ({ abs, rel: relative(abs) }))
    .filter(({ rel }) => !EXCLUDED.some((pattern) => pattern.test(rel)) && !CLIENT_ONLY.includes(rel))
    .sort((a, b) => (a.rel < b.rel ? -1 : 1));
}

function exportedNames(rel) {
  const source = fs.readFileSync(path.join(ROOT, rel), "utf8");
  const names = new Set();
  const declared = /^export\s+(?:async\s+)?(?:function|const|class|interface|type)\s+(\w+)/gm;
  for (const [, name] of source.matchAll(declared)) names.add(name);
  for (const [, body] of source.matchAll(/^export\s*\{([^}]*)\}/gm)) {
    for (const part of body.split(","))
      names.add(
        part
          .trim()
          .split(/\s+as\s+/)
          .pop(),
      );
  }
  return [...names].filter(Boolean);
}

function assertClientOnly() {
  const server = walk(path.join(ROOT, "src", "server"))
    .filter((abs) => !abs.endsWith(".test.ts"))
    .map((abs) => ({ rel: relative(abs), src: fs.readFileSync(abs, "utf8") }));
  for (const rel of CLIENT_ONLY) {
    if (!fs.existsSync(path.join(ROOT, rel))) fail(`client-only file not found: ${rel}`);
    for (const name of exportedNames(rel)) {
      const hit = server.find((file) => new RegExp(`\\b${name}\\b`).test(file.src));
      if (hit) fail(`${rel} is client-only, but src/server references "${name}" in ${hit.rel}`);
    }
  }
}

function pinnedVersions() {
  const lock = JSON.parse(fs.readFileSync(path.join(ROOT, "package-lock.json"), "utf8"));
  return PINNED_DEPS.map((name) => {
    const version = lock.packages?.[`node_modules/${name}`]?.version;
    if (typeof version !== "string") fail(`package-lock.json has no resolved version for ${name}`);
    return `${name}@${version}`;
  });
}

function cacheVersion() {
  const hash = createHash("sha256");
  for (const pinned of pinnedVersions()) hash.update(pinned).update("\0");
  for (const { rel, abs } of hashedFiles()) {
    hash.update(rel).update("\0").update(fs.readFileSync(abs, "utf8")).update("\0");
  }
  return `sha-${hash.digest("hex").slice(0, 12)}`;
}

function main() {
  const args = process.argv.slice(2);
  const unknown = args.filter((arg) => arg !== "--check");
  if (unknown.length > 0) fail(`unknown argument: ${unknown.join(" ")}`);
  assertClientOnly();

  const version = cacheVersion();
  const content = `${GEN_HEADER}export const CACHE_VERSION = "${version}";\n`;
  if (fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8") === content) {
    console.log(`gen:cache-version ok (${version})`);
    return;
  }
  if (args.includes("--check")) fail("stale cache version: run npm run gen:cache-version");
  fs.writeFileSync(OUT, content);
  console.log(`gen:cache-version updated (${version})`);
}

try {
  main();
} catch (err) {
  fail(err instanceof Error ? err.message : String(err));
}
