// @ts-check
// Generation script for src/shared/config/cache-version.gen.ts.
const fs = require("fs");
const path = require("path");
const { walkTs, stripComments } = require("./_util.cjs");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "src", "shared", "config", "cache-version.gen.ts");

const HASH_INPUT_DIRS = [
  path.join(ROOT, "src", "server", "sources"),
  path.join(ROOT, "src", "server", "parsers"),
  path.join(ROOT, "src", "server", "config"),
  path.join(ROOT, "src", "server", "infra"),
  path.join(ROOT, "src", "server", "context.ts"),
  path.join(ROOT, "src", "shared", "types"),
  path.join(ROOT, "src", "shared", "config"),
  path.join(ROOT, "src", "shared", "utils"),
];

const GEN_HEADER = `// Generated by scripts/gen-cache-version.cjs — do not edit.
`;

function collectFiles() {
  const files = [];
  for (const input of HASH_INPUT_DIRS) {
    if (fs.statSync(input).isFile()) {
      files.push(input);
      continue;
    }
    files.push(...walkTs(input));
  }
  return [...new Set(files)].filter((f) => f !== OUT).sort();
}

function hashFiles() {
  // eslint-disable-next-line global-require
  const { createHash } = require("crypto");
  const hash = createHash("sha256");
  for (const file of collectFiles()) {
    hash.update(path.relative(ROOT, file).replaceAll("\\", "/"));
    hash.update("\0");
    hash.update(stripComments(fs.readFileSync(file, "utf8")).replace(/\s+/g, " "));
    hash.update("\0");
  }
  return hash.digest("hex").slice(0, 12);
}

function main() {
  const version = `sha-${hashFiles()}`;
  const content = `${GEN_HEADER}export const CACHE_VERSION = "${version}";\n`;
  const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (existing === content) {
    console.log(`gen:cache-version ok (${version})`);
    return;
  }
  fs.writeFileSync(OUT, content);
  console.log(`gen:cache-version updated (${version})`);
}

main();
