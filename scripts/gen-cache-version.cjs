const fs = require("fs");
const path = require("path");
const { createHash } = require("crypto");
const { stripComments } = require("./script-utils.cjs");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "src", "shared", "config", "cache-version.gen.ts");

// Every file under these roots must be in HASHED or IGNORED: one in neither fails the run.
const DATA_LAYER_ROOTS = ["src/contract", "src/server", "src/shared", "worker"];

// Only the packages the Worker ships: a devDependency bump must not cut every cached payload.
function runtimeDependencyVersions() {
  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
  const lock = JSON.parse(fs.readFileSync(path.join(ROOT, "package-lock.json"), "utf8"));
  return Object.keys(manifest.dependencies ?? {})
    .sort()
    .map((name) => {
      const version = lock.packages?.[`node_modules/${name}`]?.version;
      if (typeof version !== "string") fail(`package-lock.json has no resolved version for runtime dependency ${name}`);
      return `${name}@${version}`;
    });
}

// CACHE_VERSION hashes exactly this set: an edit here cuts every cached payload, and a stale path
// fails the run. A trailing "/" covers a subtree.
const HASHED = [
  "src/contract/",
  "src/server/context.ts",
  "src/server/config/",
  "src/server/infra/",
  "src/server/parsers/",
  "src/server/routes/",
  "src/server/sources/",
  "src/shared/config/",
  "src/shared/types/",
  "src/shared/utils/",
  "worker/",
];

// Deliberately outside the version: editing one must not cold-fetch every key for every user.
const IGNORED = [
  { match: /\.test\.tsx?$/, reason: "test-only: reachable only from the vitest run" },
  { match: /^src\/server\/sources\/test-fixtures\.ts$/, reason: "test-only fixture payloads" },
  { match: /^src\/server\/test-helpers\.ts$/, reason: "test-only runtime helpers" },
  { match: /^src\/shared\/config\/cache-version\.gen\.ts$/, reason: "generated by this script" },
  { match: /^src\/shared\/i18n\//, reason: "UI copy rendered by the client, never cached" },
  { match: /^src\/server\/http\//, reason: "response header policy: headers, not payload bytes" },
];

const GEN_HEADER = `// Generated by scripts/gen-cache-version.cjs — do not edit.
`;

function fail(message) {
  console.error(`gen:cache-version ${message}`);
  process.exit(1);
}

function walkFiles(dir) {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walkFiles(full));
    else files.push(full);
  }
  return files;
}

function matches(entry, rel) {
  return entry.endsWith("/") ? rel.startsWith(entry) : rel === entry;
}

function collectHashed() {
  const hit = new Set();
  const hitIgnore = new Set();
  const hashed = [];
  for (const root of DATA_LAYER_ROOTS) {
    const abs = path.join(ROOT, root);
    if (!fs.existsSync(abs)) fail(`missing data-layer root: ${root}`);
    for (const file of walkFiles(abs)) {
      const rel = path.relative(ROOT, file).replaceAll("\\", "/");
      const ignored = IGNORED.findIndex((entry) => entry.match.test(rel));
      if (ignored >= 0) {
        hitIgnore.add(ignored);
        continue;
      }
      const at = HASHED.findIndex((entry) => matches(entry, rel));
      if (at < 0) fail(`uncovered file: ${rel} (add it to HASHED, or to IGNORED with a reason)`);
      hit.add(at);
      hashed.push({ rel, abs: file });
    }
  }
  HASHED.forEach((entry, i) => {
    if (!hit.has(i)) fail(`stale HASHED entry "${entry}" matches no file`);
  });
  IGNORED.forEach((entry, i) => {
    if (!hitIgnore.has(i)) fail(`stale IGNORED entry ${entry.match} matches no file`);
  });
  return hashed.sort((a, b) => (a.rel < b.rel ? -1 : 1));
}

function cacheVersion() {
  const hash = createHash("sha256");
  for (const pinned of runtimeDependencyVersions()) {
    hash.update(pinned);
    hash.update("\0");
  }
  for (const { rel, abs } of collectHashed()) {
    // Comment-free view: formatting changes may invalidate the version too, which is safer than
    // reusing a payload shaped by an unrecognised regular-expression change.
    hash.update(rel);
    hash.update("\0");
    hash.update(stripComments(fs.readFileSync(abs, "utf8")));
    hash.update("\0");
  }
  return hash.digest("hex").slice(0, 12);
}

function main() {
  if (process.argv.length > 2) fail(`unknown argument: ${process.argv.slice(2).join(" ")}`);

  const version = `sha-${cacheVersion()}`;
  const content = `${GEN_HEADER}export const CACHE_VERSION = "${version}";\n`;
  const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (existing === content) {
    console.log(`gen:cache-version ok (${version})`);
    return;
  }
  fs.writeFileSync(OUT, content);
  console.log(`gen:cache-version updated (${version})`);
}

try {
  main();
} catch (err) {
  fail(`failed: ${err instanceof Error ? err.message : String(err)}`);
}
